    // ── XOR ──────────────────────────────────────────────────────────────────

    private static string Decode(byte[] data)
    {
        var result = new byte[data.Length];
        for (var i = 0; i < data.Length; i++)
            result[i] = (byte)(data[i] ^ XorKey[i % XorKey.Length]);
        return Encoding.UTF8.GetString(result);
    }

    // ── DPAPI — protege chaves salvas em disco (por usuário Windows) ──────────

    private const string DpapiPrefix = "DPAPI:";

    /// <summary>Criptografa um valor com DPAPI antes de salvar no disco.</summary>
    public static string Protect(string plainText)
    {
        if (string.IsNullOrEmpty(plainText)) return plainText;
        if (plainText.StartsWith(DpapiPrefix)) return plainText; // já protegido
        try
        {
            var data      = Encoding.UTF8.GetBytes(plainText);
            var encrypted = ProtectedData.Protect(data, XorKey, DataProtectionScope.CurrentUser);
            return DpapiPrefix + Convert.ToBase64String(encrypted);
        }
        catch { return plainText; }
    }

    /// <summary>Descriptografa um valor protegido por DPAPI.</summary>
    public static string Unprotect(string stored)
    {
        if (string.IsNullOrEmpty(stored)) return stored;
        if (!stored.StartsWith(DpapiPrefix)) return stored; // texto plano (legado)
        try
        {
            var encrypted = Convert.FromBase64String(stored[DpapiPrefix.Length..]);
            var data      = ProtectedData.Unprotect(encrypted, XorKey, DataProtectionScope.CurrentUser);
            return Encoding.UTF8.GetString(data);
        }
        catch { return stored; }
    }
